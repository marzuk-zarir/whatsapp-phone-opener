/**
 * Sort by priority group, then priority order, then country name.
 * @param {Country[]} list
 * @returns {Country[]}
 */
export function sortCountries(list) {
  return [...list].sort(
    (a, b) =>
      a.priorityGroup - b.priorityGroup ||
      a.priorityOrder - b.priorityOrder ||
      collator.compare(a.name, b.name)
  );
}

/**
 * Filter by name, ISO code, secondary ISO code, or calling code.
 * Preserves the dataset ordering.
 * @param {Country[]} list
 * @param {string} query
 * @returns {Country[]}
 */
export function filterCountries(list, query) {
  const needle = query.trim().toLowerCase();
  if (!needle) return list;

  const codeNeedle = needle.startsWith('+') ? needle.slice(1) : needle;

  return list.filter((country) => {
    if (country.name.toLowerCase().includes(needle)) return true;
    if (country.isoCode.toLowerCase() === needle) return true;
    if (country.secondaryIsoCode?.toLowerCase() === needle) return true;
    if (country.callingCode === codeNeedle || country.callingCode.startsWith(codeNeedle)) return true;
    return false;
  });
}
